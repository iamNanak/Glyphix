// Generates src/render/three/asciiGlyphs.ts: the outlines of every ASCII-effect glyph, read from the
// bundled JetBrains Mono (OFL, public/fonts). Embedding outlines lets the effect build its charset
// atlases synchronously and identically everywhere (no font fetch before the first frame or export).
// Usage: node scripts/gen-ascii-glyphs.mjs
import fs from 'node:fs';
import * as hb from 'harfbuzzjs';

const FONT = 'public/fonts/JetBrainsMono.ttf';
const WEIGHT = 500;
// Keep in sync with CHARSETS in src/render/three/asciiAtlas.ts (the generator only needs the union).
const CHARS = [
  ' .:-=+*#%@',
  ' ░▒▓█',
  " .'`^\",:;Il!i><~+_-?][}{1)(|\\/tfjrxnuvczXYUJCLQ0OZmwqpdbkhao*#MW&8%B@$",
  ' 01',
  '|-/\\', // edge glyphs
].join('');

const data = fs.readFileSync(FONT);
const face = new hb.Face(new hb.Blob(data.buffer.slice(data.byteOffset, data.byteOffset + data.byteLength)));
const font = new hb.Font(face);
font.setVariations([new hb.Variation('wght', WEIGHT)]);
const ext = font.hExtents();

const glyphs = {};
for (const ch of [...new Set(CHARS)].sort()) {
  const gid = font.glyph(ch.codePointAt(0));
  if (!gid) throw new Error(`JetBrains Mono has no glyph for ${JSON.stringify(ch)}`);
  // Integer font units are far finer than the 64 px atlas cell (1 unit ≈ 0.06 px).
  glyphs[ch] = font.glyphToPath(gid).replace(/-?\d+(\.\d+)?/g, (n) => String(Math.round(Number(n))));
}

const body = Object.entries(glyphs)
  .map(([ch, path]) => `  ${JSON.stringify(ch)}: '${path}',`)
  .join('\n');
fs.writeFileSync(
  'src/render/three/asciiGlyphs.ts',
  `// Generated by scripts/gen-ascii-glyphs.mjs — do not edit.
// Glyph outlines (font units, y up) from JetBrains Mono ${WEIGHT} (SIL Open Font License 1.1, see
// public/fonts/JetBrainsMono-OFL.txt), used to rasterise the ASCII effect's charset atlases.
export const ASCII_FONT = { upem: ${face.upem}, advance: ${font.glyphHAdvance(font.glyph(48))}, ascender: ${ext.ascender}, descender: ${ext.descender} };

export const ASCII_GLYPHS: Record<string, string> = {
${body}
};
`,
);
console.log(`${Object.keys(glyphs).length} glyphs, ${fs.statSync('src/render/three/asciiGlyphs.ts').size} bytes`);
